    plot_loss_vs_sample_size(grid_sample_nums, grid_flux,
                             active_sample_flux_nums, active_flux, mode="flux")
    print("Plotting lags")
    plot_loss_vs_sample_size(grid_sample_nums, grid_lags,
                             active_sample_lags_nums, active_lags, mode="lags")
    
