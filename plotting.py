def residual_plots(egrid, pred, da, fname, title, mname, log = False, 
                   norm = False, mode = "flux"):
    """
    Plots comparison between NN model output and rtdist output with a 
    percentage residual subplot underneath.

    Parameters
    ----------
    egrid : ndarray
        energy grid to plot points on (x-axis).
    pred : ndarray
        NN model output to be plotted.
    da : ndarray
        rtdist model output to be plotted.
    fname : string
        file save location.
    title : string
        title of plot.
    mname : string
        model name.
    log : bool, optional
        If True, change y-label to be log(mode). The default is False.
    norm : bool, optional
        If True, enforce maximum range on residuals. The default is False.
    mode : string, optional
        the type of model output to be compared. Is placed as the x-label.
        The default is "flux".

    """
    fig, axs = plt.subplots(2,1,sharex=True)
    axs[0].plot(egrid,pred,c="blue",label="NN model")
    axs[0].plot(egrid,da,c="r",label="Truth",lw=1.)
    axs[0].legend()
    axs[0].set_title(title)
    if log == True:
        axs[0].set_ylabel(f"Log({mode})")
        axs[0].set_yscale("log")
    else:
        axs[0].set_ylabel(f"{mode}")
    axs[1].scatter(egrid,(da-pred)/da,s=0.5)
    axs[1].set_ylabel("Residuals")
    axs[1].set_xlabel("Energy in keV")
    axs[1].axhline(y=0.01,ls="--",color="orange")
    axs[1].axhline(y=-0.01,ls="--",color="orange")
    max_res = np.absolute((da-pred)/da).max()
    if max_res > 1 and norm == True:
        axs[1].set_ylim(-1,1)
    plt.tight_layout()
    plt.savefig(f"samples/{mname}_{fname}.png")
    plt.close()
    
