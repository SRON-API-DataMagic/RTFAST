    grid_lags_name = [f"grid_{i}" for i in range(5,11)]
    grid_flux_scaler = [f"mag_grid_{i}_flux_scaler.bin" for i in range(5,11)]
    grid_lags_scaler = [f"mag_grid_{i}_lags_scaler.bin" for i in range(5,11)]
