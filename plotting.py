def model_load(model_loc, egrid, lags = None):
    """
    Loads neural network model states from the disk. Can load both the flux and
    lag neural network model types.

    Parameters
    ----------
    model_loc : string
        location of the file with neural network parameters.
    egrid : ndarray
        energy grid values.
    lags : any, optional
        If this is not None, assumes loading a time lags model. The default is 
        None.

    Returns
    -------
    model : pytorch model
        the desired pytorch neural network model.

    """
    if lags == None:
        model = network.MagFluxNetwork(5, len(egrid))
    else:
        model = network.MagLagsNetwork(5, len(egrid))
    model.load_state_dict(torch.load(model_loc))
    model.eval()
    return model
    
def residual_sorting(df,indexing):
    """
    Sorts residual dataframe by the given index and returns the 0.01, 0.25, 
    0.5, 0.75 percentile values as tick labels

    Parameters
    ----------
    df : pandas dataframe
        dataframe containing residuals and their corresponding parameters.
    indexing : string
        name of the column to sort dataframe by.

    Returns
    -------
    tick : list
        list of tick values index.
    ticklabel : list
        list of tick values.

    """
    df.sort_values(by=indexing,inplace=True,ignore_index=True)
    percents = [0,0.25,0.5,0.75]
    tick = []
    ticklabel = []
    for p in percents:
        tick.append(int(len(df)*p))
        ticklabel.append(f"{df[indexing][int(len(df)*p)]:.2f}")
    return tick,ticklabel

def residual_computation(dataloader, model, scaler, mode, dec_mag=False):
    """
    Computes and records residual differences between neural network outputs
    and rtdist outputs. Records them with the parameters. For data and model
    outputs below a threshold, we consider the residual difference to be 0.

    Parameters
    ----------
    dataloader : pytorch dataloader
        contains test data and parameters.
    model : pytorch model
        neural network model to compare results to.
    scaler : scikitlearn MinMaxScaler
        scaler to change network output back to real output.
    mode : string
        signifies if using a time lags or flux model.

    Returns
    -------
    dataframe : pandas dataframe
        contains residuals and parameters.
    ticks : list
        list of lists of tick indexes for each parameter.
    ticklabels : list
        list of lists of tick values for each parameter.

    """
    pars = [[] for i in range(5)]
    logged = [0,2,3,4,7,8,10,11,12,13,19]
    logged = [1,2,3,4]
    pars_list = ["height","a","inc","rin","rout","z","Gamma","distance","Afe","logNe","kte",
              "nH","boost","mass","honr","b1","b2","phiAB","g","Anorm"]
    pars_list = ["a","inc","rin","rout","distance"]
    residuals = []
    for batch, (D,P) in enumerate(tqdm(dataloader)):
        for i in range(len(pars)):
            if i in logged:
                pars[i].append(10**P[0][i].item())
            else:
                pars[i].append(P[0][i].item())
        if mode == "flux":
            if dec_mag == False:
                pred = model(P).detach().numpy()
                pred = 10**(inverse(scaler,pred))
            else:
                mag_pred, dec_pred = model(P)
                dec_pred = (dec_pred*9) + 1
                pred = dec_pred.detach().numpy() * (10**np.floor(inverse(scaler,
                                                        mag_pred.detach().numpy())))
        else:
            if dec_mag == False:
                pred, I_pred = model(P)
                pred = 10**(inverse(scaler,pred.detach().numpy()))
            else:
                mag_pred, dec_pred, I_pred = model(P)
                dec_pred = (dec_pred*9) + 1
                pred = (dec_pred.detach().numpy() * 
                        (10**np.round(inverse(scaler,
                                              mag_pred.detach().numpy()))))
        if mode != "flux":
            pred = pred*np.where(I_pred.detach().numpy() > 0.5, 1, -1)
        resid = (D-pred)/D
        resid = resid.numpy()
        try:
            if mode == "flux":
                resid = np.where((np.abs(D)<=1e-38)&(np.abs(pred)<=1e-38),0,resid)
            else:
                resid = np.where((np.abs(D)<=1e-6)&(np.abs(pred)<=1e-6),0,resid)
        except:
            pass
        resid = np.absolute(np.asarray(resid))
        residuals.append(resid)
        
    residuals = np.squeeze(np.asarray(residuals))
    obj_residuals = []
    for res in residuals:
        obj_residuals.append(Residual(res))
    
    data = {}
    for i,label in enumerate(pars_list):
        data[label] = pars[i]
    data["residuals"] = obj_residuals
    
    dataframe = pd.DataFrame.from_dict(data)
    ticks = []
    ticklabels = []
    for label in pars_list:
        tick, ticklabel = residual_sorting(dataframe, label)
        ticks.append(tick)
        ticklabels.append(ticklabel)
    
    return (dataframe, ticks, ticklabels)

def calculate_loss(testing_dataloader, model, scaler, mode = "flux", 
                   dec_mag = False):
    """
    

    Parameters
    ----------
    testing_dataloader : TYPE
        DESCRIPTION.
    model : TYPE
        DESCRIPTION.
    scaler : TYPE
        DESCRIPTION.
    mode : TYPE, optional
        DESCRIPTION. The default is "flux".

    Returns
    -------
    residuals : TYPE
        DESCRIPTION.

    """
    residuals = []
    for batch, (D,P) in enumerate(tqdm(testing_dataloader)):
        if dec_mag == False:
            if mode == "flux":
                pred = model(P)
            else:
                pred, I_pred = model(P)
        else:
            if mode == "flux":
                mag_pred, dec_pred = model(P)
            else:
                mag_pred, dec_pred, I_pred = model(P)
            
            dec_pred = (dec_pred.detach().numpy()*9) + 1
            pred = dec_pred * (10**np.round(inverse(scaler,mag_pred.detach().numpy())))
        
        if mode != "flux":
            pred = pred*np.where(I_pred.detach().numpy() > 0.5, 1, -1)
        resid = (D-pred)/D
        resid = resid.numpy()
        
        try:
            if mode == "flux":
                resid = np.where((np.abs(D)<=1e-38)&(np.abs(pred)<=1e-38),
                                 0,resid)
            else:
                resid = np.where((np.abs(D)<=1e-6)&(np.abs(pred)<=1e-6),
                                 0,resid)
        except:
            print("Thresholds failed")
            pass
        residuals.append(np.absolute(np.asarray(resid)))
    residuals = np.asarray(residuals)
    return residuals

