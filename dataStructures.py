class FluxData(Dataset):
    def __init__(self, pars, data, scaler, scaler_name, pars_list, 
                 negatives = [], logged = [], scaling=False, end=-1 , 
                 parallel = False):
        super().__init__()
        self.pars = torch.Tensor(pars.to_numpy()[:,pars_list].astype(float))
        self.pars[:,negatives] = -self.pars[:,negatives]
        self.pars[:,logged] = np.log10(self.pars[:,logged])
        self.data = torch.Tensor(data)
        self.scaling = scaling
        self.scaler_name = scaler_name
        self.lower_threshold = 1e-11
        if scaling == True:
            print(f"Creating scaler with name {scaler_name}")
            self.scaler = scaler
            self.scaler_create(end)
        else:
            self.scaler = load(f'scalers/{self.scaler_name}')

    def __len__(self):
        return self.data.shape[0]

    def __getitem__(self,idx):
        datum = self.data[idx]
        datum = self.standardize(datum)
        parameters = self.pars[idx].double()
        return datum, parameters

    def standardize(self, D):
        """
        Filters 0 flux and converts to smallest non-zero value. Then standard
        scales the energy bins.
        """
        D[D<=self.lower_threshold] = self.lower_threshold
        D = np.log10(D)
        D = self.scaler.transform(D)
        D = torch.from_numpy(D)
        D = D.double()
        return D
    
    def scaler_create(self,end):
        """
        Creates and loads the scaler for the dataset.

        Returns
        -------
        None.

        """
        data = []
        for datum in self.data:
            data.append(datum)
        D = np.concatenate(data,axis=0)
        D[D<=self.lower_threshold] = self.lower_threshold
        D = np.log10(D)
        data = self.scaler.fit(D)
        dump(self.scaler, f'scalers/{self.scaler_name}', compress=True)
        return

class FluxDataDisk(Dataset):
    """
    A class that inherits from torch.Dataset that returns both the data from
    the model evaluation and the parameters used to generate the model.
    
    Attributes
    ----------
    par_list : np.ndarray
        Contains the list of parameters used to generate the model.
    data : np.ndarray
        Contains the data generated by the model
    """
    
    def __init__(self, labels, scaler, scaler_name, pars_list, negatives = [], 
                 logged = [], scaling=False, end=-1 , parallel = False):
        super().__init__()
        self.labels = pd.read_csv(labels)
        self.pars_list = pars_list
        self.negatives = negatives
        self.logged = logged
        self.scaling = scaling
        self.scaler_name = scaler_name
        self.lower_threshold = 1e-11
        if scaling == True:
            print(f"Creating scaler with name {scaler_name}")
            self.scaler = scaler
            self.scaler_create(end)
        else:
            self.scaler = load(f'scalers/{self.scaler_name}')
    
    def __len__(self):
        return len(self.labels)
    
    def __getitem__(self, idx):
        #retrieve location of the spectra to load
        location = self.labels.iloc[idx,-1]
        #retrieve parameters 
        parameters = self.labels.iloc[idx,self.pars_list].astype(float)
        #convert parameters to log space
        parameters.iloc[self.negatives] = -parameters.iloc[self.negatives]
        parameters.iloc[self.logged] = np.log10(parameters.iloc[self.logged])
        parameters = torch.tensor(parameters)
        #load spectra
        datum = np.loadtxt(location).reshape(1, -1)
        #scale spectra by energy bin to normalized space
        datum = self.standardize(datum)
        return datum, parameters
    
    def standardize(self, D):
        """
        Filters 0 flux and converts to smallest non-zero value. Then standard
        scales the energy bins.
        """
        D[D<=self.lower_threshold] = self.lower_threshold
        D = np.log10(D)
        D = self.scale(D)
        D = torch.from_numpy(D)
        D = D.double()
        return D
    
    def scaler_create(self,end):
        """
        Creates and loads the scaler for the dataset.

        Returns
        -------
        None.

        """
        data = []
        for file in self.labels.iloc[:end,-1]:
            data.append(np.loadtxt(file).reshape(1, -1))
        D = np.concatenate(data,axis=0)
        D[D<=self.lower_threshold] = self.lower_threshold
        D = np.log10(D)
        data = self.scaler.fit(D)
        dump(self.scaler, f'scalers/{self.scaler_name}', compress=True)
        return
    
    def scale(self, data):
        """
        Standard scales the logarithm spaced data by energy bin and saves the
        standard scaler for future use.

        Parameters
        ----------
        data : np.ndarray
            Array of spectra in the logspace.

        Returns
        -------
        scaled_data : np.ndarray
            Scaled array of spectra in the logspace.

        """
        scaled_data = self.scaler.transform(data)
        return scaled_data

