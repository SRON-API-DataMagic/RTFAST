class Parameters():
    """
    Class that holds parameters and their transformed versions for both neural
    networks and rtdist generation.
    """
    def __init__(self,nn_pars,pars_list,negatives,logged):
        self.nn_pars = nn_pars
        self.pars_list = pars_list
        self.negatives = negatives
        self.logged = logged
        self.flux = self.nn_pars_to_rtdist(nn_pars,0)
        self.lags = self.nn_pars_to_rtdist(nn_pars,6)
        
    def nn_pars_to_rtdist(self,nn_pars,ReIm):
        """
        Converts sampled paramters for neural network training into correct format
        for use in generating data and adds non-sampled parameters needed by the
        model. This is the generic form in which the list of sampled parameters 
        and manipulations are passed to the function

        Parameters
        ----------
        nn_pars : np.ndarray
            array of sampled parameters.
        ReIm : int
            value of ReIm from rtdist to determine the type of output rtdist 
            produces.
        pars_list : list
            list of indexes of parameters.
        negatives : list
            list of indexes of parameters that need to be turned positive.
        logged : list
            list of indexes of parameters that need to be transformed to power of
            10.

        Returns
        -------
        converted_pars : np.ndarray
            array of parameters to be used for parameter generation.

        """
        #set up base parameters which can be used to fix parameter sets to
        #reasonable values
        pars_base = [6,0.9,57,-1,2e4,0.024917,2.45,1e5,1,17,50.,5,1,3e6,0.02,0,0,0,
                     0,ReIm,0,-0.8,0.3,2.2e-4,1,1.]
        #set up base parameters to transform according to sampled parameters
        converted_pars = []
        for i in range(nn_pars.shape[0]):
            converted_pars.append(pars_base)
        converted_pars = np.asarray(converted_pars)
        #iterate through 
        for i, parameter in enumerate(self.pars_list):
            if parameter in self.logged:
                converted_pars[:,parameter] = 10**nn_pars[:,i]
            else:
                converted_pars[:,parameter] = nn_pars[:,i]
            if parameter in self.negatives:
                converted_pars[:,parameter] = -converted_pars[:,parameter]
        return converted_pars
    
    def add_pars(self,new_pars):
        """
        Adds new parameters to parameter set, as well as converts them to
        rtdist generational form.

        Parameters
        ----------
        new_pars : np.ndarray
            array of new sampled parameters for neural network.

        Returns
        -------
        None.

        """
        self.nn_pars = np.concatenate((self.nn_pars,new_pars),axis = 0)
        new_flux = self.nn_pars_to_rtdist(new_pars,0)
        new_lags = self.nn_pars_to_rtdist(new_pars,6)
        self.flux = np.concatenate((self.flux,new_flux),axis = 0)
        self.lags = np.concatenate((self.lags,new_lags),axis = 0)
    
class PCADataset(Dataset):
    
    def __init__(self,data_loc,pars_list,negatives,logged,threshold = 1e-11,
                 scale_bool = True, comps = 1,PCA_loc="scalers/PCA_flux.bin",
                 comp_loc="scalers/comp_flux.bin",
                 spec_scal_loc="scalers/spec_flux.bin",force = False):
        data_table = pd.read_csv(data_loc)
        self.threshold = threshold
        self.force = force
        self.scale_bool = scale_bool
        self.PCA_loc = PCA_loc
        self.comp_loc = comp_loc
        self.spec_scal_loc = spec_scal_loc
        self.comps = comps
        self.locations = data_table.iloc[:,-1]
        self.pars = np.asarray(data_table.iloc[:,pars_list])
        self.pars_list = pars_list
        self.rtdist_to_nn(negatives,logged)
        self.data_load()
        self.data = torch.Tensor(self.data)
        self.pars = torch.Tensor(self.pars)
        self.data.float()
        self.pars.float()
        
    def __len__(self):
        return self.data.shape[0]
    
    def __getitem__(self,idx):
        return self.data[idx], self.pars[idx]
    
    def rtdist_to_nn(self,negatives,logged):
        """
        Converts rtdist parameters into neural network friendly form.

        Parameters
        ----------
        negatives: list
            list of indexes of parameters to be turned positive due to being
            a negative value in rtdist
        logged: list
            list of indexes of parameters for their logarithm to be inputted
            into the network

        """
        for i, parameter in enumerate(self.pars_list):
            if parameter in negatives:
                self.pars[:,i] = -self.pars[:,i]
            if parameter in logged:
                self.pars[:,i] = np.log10(self.pars[:,i])
    
    def data_load(self):
        
        def file_load(file):
            return np.loadtxt(file).reshape(1, -1)
        
        data = Parallel(n_jobs=20,verbose=1)(delayed(file_load)(file) for file in self.locations)
        D = np.concatenate(data,axis=0)
        D[D<self.threshold] = self.threshold
        D = np.log10(D)
        self.data = D
        self.scale()
    
    def scale(self):
        self.spectra_scaler(self.spec_scal_loc)
        self.PCA(self.PCA_loc,self.comps)
        self.component_scaler(self.comp_loc)
        return
    
    def spectra_scaler(self,scaler_loc):
        if self.scale_bool == True:
            self.spec_scaler = StandardScaler()
            self.data = self.spec_scaler.fit_transform(self.data)
            dump(self.spec_scaler,scaler_loc)
        else:
            self.spec_scaler = load(scaler_loc)
            self.data = self.spec_scaler.transform(self.data)
        return
    
    def PCA(self,scaler_loc,comp = 1):
        if self.force == True:
            self.pca = PCA(n_components = comp)
            self.pca.fit(self.data)
            self.data = self.pca.transform(self.data)
            print(f"Achieved explained variance of {sum(self.pca.explained_variance_ratio_)*100}% with {comp} components")
            print(f"Distribution of explained variance is {self.pca.explained_variance_ratio_}")
            dump(self.pca,scaler_loc)
            return
        if self.scale_bool == True:
            print(f"Attempting n_comp = {comp}")
            self.pca = PCA(n_components = comp)
            self.pca.fit(self.data)
            if sum(self.pca.explained_variance_ratio_) < 0.99999:
                print(f"Currently achieved explained variance of {sum(self.pca.explained_variance_ratio_)*100}%")
                self.PCA(scaler_loc,comp+1)
            else:
                print("Successfully describes 99.99% of variance")
                self.data = self.pca.transform(self.data)
                dump(self.pca,scaler_loc)
            return
        else:
            self.pca = load(scaler_loc)
            self.data = self.pca.transform(self.data)
            return
    def component_scaler(self,scaler_loc):
        if self.scale_bool == True:
            self.PCA_scaler = StandardScaler()
            self.data = self.PCA_scaler.fit_transform(self.data)
            dump(self.PCA_scaler,scaler_loc)
        else:
            self.PCA_scaler = load(scaler_loc)
            self.data = self.PCA_scaler.transform(self.data)
        return

class PCALagsDataset(PCADataset):
    
    def __init__(self,data_loc,pars_list,negatives,logged,threshold = 1e-6,
                 scale_bool = True, comps = 1,PCA_loc="scalers/PCA_lags.bin",
                 comp_loc="scalers/comp_lags.bin"):
        super().__init__(data_loc,pars_list,negatives,logged,threshold,
                     scale_bool, comps, PCA_loc, comp_loc)
    
    def data_load(self):
        """
        Loads data, takes the logarithm and makes the break between the postive
        and negative threshold continuous for PCA compatible space.

        Returns
        -------
        None.

        """
        data = []
        for file in tqdm.tqdm(self.locations):
            data.append(np.loadtxt(file).reshape(1, -1))
        D = np.concatenate(data,axis=0)
        D[(D<self.threshold)&(D>0)] = self.threshold
        D[(D>-self.threshold)&(D<0)] = -self.threshold
        D[D<0] = -(np.log10(np.abs(D[D<0]))+6)
        D[D>0] = np.log10(np.abs(D[D>0]))+6
        self.data = D
        self.scale()